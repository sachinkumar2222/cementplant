// Card styles API
app.get(["/api/card-styles", "/api/styles"], (req, res) => {
  const jsonPath = path.join(widgetDir, "custom-styles.json");
  if (fs.existsSync(jsonPath)) {
    try {
      const data = JSON.parse(fs.readFileSync(jsonPath, "utf-8"));
      return res.json({ ok: true, styles: data });
    } catch (e) {
      return res.status(500).json({ ok: false, error: e.message });
    }
  }
  res.json({ ok: true, styles: {} });
});

app.post(["/api/card-styles", "/api/styles"], (req, res) => {
  try {
    const styles = req.body || {};
    const jsonPath = path.join(widgetDir, "custom-styles.json");
    const cssPath = path.join(widgetDir, "css", "custom-cards.css");

    fs.writeFileSync(jsonPath, JSON.stringify(styles, null, 2), "utf-8");

    // Helper to generate CSS
    let css = `/* Generated by Widget Visual Editor */\n\n`;
    const standardCards = [
      { key: "preheating", selector: 'body[data-card="preheating"]' },
      { key: "kiln", selector: 'body[data-card="kiln"]' },
      { key: "cooler", selector: 'body[data-card="cooler"]' }
    ];

    standardCards.forEach(({ key, selector }) => {
      const s = styles[key];
      if (!s) return;
      css += `${selector} .card, html ${selector} .card {\n`;
      if (s.cardWidth) css += `  width: ${s.cardWidth}px !important;\n`;
      if (s.cardPaddingY || s.cardPaddingX) css += `  padding: ${s.cardPaddingY || 13}px ${s.cardPaddingX || 15}px !important;\n`;
      if (s.cardRadius) css += `  border-radius: ${s.cardRadius}px !important;\n`;
      if (s.cardGap) css += `  gap: ${s.cardGap}px !important;\n`;
      css += `}\n`;
      if (s.headerPaddingBottom) css += `${selector} .card-header {\n  padding-bottom: ${s.headerPaddingBottom}px !important;\n}\n`;
      if (s.titleFontSize) css += `${selector} .card-title, ${selector} #title, html ${selector} .card-title {\n  font-size: ${s.titleFontSize}px !important;\n}\n`;
      if (s.iconFontSize) css += `${selector} .card-icon {\n  font-size: ${s.iconFontSize}px !important;\n}\n`;
      if (s.sensorBoxPaddingY || s.sensorBoxPaddingX || s.sensorBoxRadius) {
        css += `${selector} .sensor-box {\n`;
        if (s.sensorBoxPaddingY || s.sensorBoxPaddingX) css += `  padding: ${s.sensorBoxPaddingY || 8}px ${s.sensorBoxPaddingX || 10}px !important;\n`;
        if (s.sensorBoxRadius) css += `  border-radius: ${s.sensorBoxRadius}px !important;\n`;
        css += `}\n`;
      }
      if (s.sensorLabelFontSize) css += `${selector} .sensor-label {\n  font-size: ${s.sensorLabelFontSize}px !important;\n}\n`;
      if (s.sensorValueFontSize) css += `${selector} .sensor-value {\n  font-size: ${s.sensorValueFontSize}px !important;\n}\n`;
      if (s.sensorUnitFontSize) css += `${selector} .sensor-unit {\n  font-size: ${s.sensorUnitFontSize}px !important;\n}\n`;
      if (s.controlPaddingY || s.controlPaddingX || s.controlGap || s.controlRadius) {
        css += `${selector} .control-row {\n`;
        if (s.controlPaddingY || s.controlPaddingX) css += `  padding: ${s.controlPaddingY || 8}px ${s.controlPaddingX || 12}px !important;\n`;
        if (s.controlGap) css += `  gap: ${s.controlGap}px !important;\n`;
        if (s.controlRadius) css += `  border-radius: ${s.controlRadius}px !important;\n`;
        css += `}\n`;
      }
      if (s.controlNameFontSize) css += `${selector} .control-name {\n  font-size: ${s.controlNameFontSize}px !important;\n}\n`;
      if (s.btnFontSize || s.btnPaddingY || s.btnPaddingX || s.btnRadius) {
        css += `${selector} .state-btn {\n`;
        if (s.btnFontSize) css += `  font-size: ${s.btnFontSize}px !important;\n`;
        if (s.btnPaddingY || s.btnPaddingX) css += `  padding: ${s.btnPaddingY || 5}px ${s.btnPaddingX || 13}px !important;\n`;
        if (s.btnRadius) css += `  border-radius: ${s.btnRadius}px !important;\n`;
        css += `}\n`;
      }
      css += `\n`;
    });

    // Hoppers
    const hopperCards = [
      { key: "hopper_gypsum", classSel: ".card-gypsum" },
      { key: "hopper_clay", classSel: ".card-clay" },
      { key: "hopper_sand", classSel: ".card-sand" },
      { key: "hopper_iron_ore", classSel: ".card-iron_ore" }
    ];

    hopperCards.forEach(({ key, classSel }) => {
      const s = styles[key] || styles.hopper;
      if (!s) return;
      css += `body[data-card="hopper"] ${classSel}, html body[data-card="hopper"] ${classSel} {\n`;
      if (s.cardWidth) css += `  width: ${s.cardWidth}px !important;\n`;
      if (s.cardPaddingY || s.cardPaddingX) css += `  padding: ${s.cardPaddingY || 16}px ${s.cardPaddingX || 16}px !important;\n`;
      if (s.cardRadius) css += `  border-radius: ${s.cardRadius}px !important;\n`;
      css += `}\n`;
      if (s.titleFontSize) {
        css += `body[data-card="hopper"] ${classSel} .card-title, body[data-card="hopper"] ${classSel} #title, html body[data-card="hopper"] ${classSel} .card-title {\n  font-size: ${s.titleFontSize}px !important;\n}\n`;
      }
      if (s.sensorValueFontSize) {
        css += `body[data-card="hopper"] ${classSel} .card-value, body[data-card="hopper"] ${classSel} #val {\n  font-size: ${s.sensorValueFontSize}px !important;\n}\n`;
      }
      if (s.sensorUnitFontSize) {
        css += `body[data-card="hopper"] ${classSel} .card-unit {\n  font-size: ${s.sensorUnitFontSize}px !important;\n}\n`;
      }
    });

    const h = styles.hopper || styles.hopper_gypsum;
    if (h) {
      css += `body[data-card="hopper"] .card, html body[data-card="hopper"] .card {\n`;
      if (h.cardWidth) css += `  width: ${h.cardWidth}px !important;\n`;
      if (h.cardPaddingY || h.cardPaddingX) css += `  padding: ${h.cardPaddingY || 16}px ${h.cardPaddingX || 16}px !important;\n`;
      if (h.cardRadius) css += `  border-radius: ${h.cardRadius}px !important;\n`;
      css += `}\n`;
      if (h.titleFontSize) {
        css += `body[data-card="hopper"] .card-title, body[data-card="hopper"] #title, html body[data-card="hopper"] .card-title {\n  font-size: ${h.titleFontSize}px !important;\n}\n`;
      }
      if (h.sensorValueFontSize) {
        css += `body[data-card="hopper"] .card-value, body[data-card="hopper"] #val {\n  font-size: ${h.sensorValueFontSize}px !important;\n}\n`;
      }
      if (h.sensorUnitFontSize) {
        css += `body[data-card="hopper"] .card-unit {\n  font-size: ${h.sensorUnitFontSize}px !important;\n}\n`;
      }
    }

    // Telemetry Cards (widget.html)
    const telemetryKeys = Object.keys(styles).filter(k => k.startsWith("telemetry_") || k === "telemetry");
    if (telemetryKeys.length > 0) {
      const t = styles.telemetry_iron_ore || styles.telemetry || styles[telemetryKeys[0]];
      if (t) {
        css += `/* TELEMETRY WIDGETS */\n`;
        css += `body[data-card="telemetry"] .load-card, html body[data-card="telemetry"] .load-card {\n`;
        if (t.cardWidth) css += `  width: ${t.cardWidth}px !important;\n`;
        if (t.cardPaddingY || t.cardPaddingX) css += `  padding: ${t.cardPaddingY || 16}px ${t.cardPaddingX || 18}px !important;\n`;
        if (t.cardRadius) css += `  border-radius: ${t.cardRadius}px !important;\n`;
        if (t.cardGap) css += `  gap: ${t.cardGap}px !important;\n`;
        css += `}\n`;
        if (t.titleFontSize) {
          css += `body[data-card="telemetry"] .material-title, html body[data-card="telemetry"] .material-title {\n  font-size: ${t.titleFontSize}px !important;\n}\n`;
        }
        if (t.iconFontSize) {
          css += `body[data-card="telemetry"] .material-icon, html body[data-card="telemetry"] .material-icon {\n  font-size: ${t.iconFontSize}px !important;\n}\n`;
        }
        if (t.sensorValueFontSize) {
          css += `body[data-card="telemetry"] .telemetry-val, html body[data-card="telemetry"] .telemetry-val {\n  font-size: ${t.sensorValueFontSize}px !important;\n}\n`;
        }
        if (t.sensorUnitFontSize) {
          css += `body[data-card="telemetry"] .telemetry-unit, html body[data-card="telemetry"] .telemetry-unit {\n  font-size: ${t.sensorUnitFontSize}px !important;\n}\n`;
        }
        if (t.btnFontSize || t.btnPaddingY || t.btnPaddingX) {
          css += `body[data-card="telemetry"] .load-status-badge, html body[data-card="telemetry"] .load-status-badge {\n`;
          if (t.btnFontSize) css += `  font-size: ${t.btnFontSize}px !important;\n`;
          if (t.btnPaddingY || t.btnPaddingX) css += `  padding: ${t.btnPaddingY || 5}px ${t.btnPaddingX || 12}px !important;\n`;
          css += `}\n`;
        }
        css += `\n`;
      }
    }

    // Hopper Dispenser Controllers (hopper-control.html)
    const dispenseKeys = Object.keys(styles).filter(k => k.startsWith("ctrl_dispense_") || k === "dispenser");
    if (dispenseKeys.length > 0) {
      const d = styles.ctrl_dispense_iron_ore || styles.dispenser || styles[dispenseKeys[0]];
      if (d) {
        css += `/* DISPENSE CONTROLS */\n`;
        css += `body[data-card="dispenser"] .card, html body[data-card="dispenser"] .card {\n`;
        if (d.cardWidth) css += `  width: ${d.cardWidth}px !important;\n`;
        if (d.cardPaddingY || d.cardPaddingX) css += `  padding: ${d.cardPaddingY || 16}px ${d.cardPaddingX || 16}px !important;\n`;
        if (d.cardRadius) css += `  border-radius: ${d.cardRadius}px !important;\n`;
        if (d.cardGap) css += `  gap: ${d.cardGap}px !important;\n`;
        css += `}\n`;
        if (d.controlNameFontSize || d.titleFontSize) {
          css += `body[data-card="dispenser"] .target-row, html body[data-card="dispenser"] .target-row {\n  font-size: ${d.controlNameFontSize || d.titleFontSize || 16}px !important;\n}\n`;
        }
        if (d.sensorValueFontSize) {
          css += `body[data-card="dispenser"] .target-input, html body[data-card="dispenser"] .target-input {\n  font-size: ${d.sensorValueFontSize}px !important;\n}\n`;
        }
        if (d.btnFontSize || d.btnPaddingY || d.btnPaddingX || d.btnRadius) {
          css += `body[data-card="dispenser"] .dispense-btn, html body[data-card="dispenser"] .dispense-btn {\n`;
          if (d.btnFontSize) css += `  font-size: ${d.btnFontSize}px !important;\n`;
          if (d.btnPaddingY || d.btnPaddingX) css += `  padding: ${d.btnPaddingY || 9}px ${d.btnPaddingX || 12}px !important;\n`;
          if (d.btnRadius) css += `  border-radius: ${d.btnRadius}px !important;\n`;
          css += `}\n`;
        }
        css += `\n`;
      }
    }

    // Actuator Power Controllers (control.html)
    const ctrlKeys = Object.keys(styles).filter(k => (k.startsWith("ctrl_") && !k.startsWith("ctrl_dispense_")) || k === "control");
    if (ctrlKeys.length > 0) {
      const c = styles.ctrl_crusher || styles.control || styles[ctrlKeys[0]];
      if (c) {
        css += `/* ACTUATOR CONTROLS */\n`;
        if (c.controlGap) {
          css += `body[data-card="control"] #buttons, html body[data-card="control"] #buttons {\n  gap: ${c.controlGap}px !important;\n}\n`;
        }
        if (c.cardWidth) {
          const btnDim = Math.min(Math.max(c.cardWidth, 36), 84);
          css += `body[data-card="control"] .power-btn, html body[data-card="control"] .power-btn {\n  width: ${btnDim}px !important;\n  height: ${btnDim}px !important;\n`;
          if (c.btnRadius !== undefined) css += `  border-radius: ${c.btnRadius}% !important;\n`;
          css += `}\n`;
        }
        if (c.iconFontSize) {
          css += `body[data-card="control"] .power-btn svg, html body[data-card="control"] .power-btn svg {\n  width: ${c.iconFontSize}px !important;\n  height: ${c.iconFontSize}px !important;\n}\n`;
        }
        if (c.titleFontSize) {
          css += `body[data-card="control"] #label, html body[data-card="control"] #label {\n  font-size: ${c.titleFontSize}px !important;\n}\n`;
        }
        css += `\n`;
      }
    }

    if (!fs.existsSync(path.join(widgetDir, "css"))) {
      fs.mkdirSync(path.join(widgetDir, "css"), { recursive: true });
    }
    fs.writeFileSync(cssPath, css, "utf-8");
    res.json({ ok: true, message: "Styles saved!" });
  } catch (err) {
    res.status(500).json({ ok: false, error: err.message });
  }
});

if (fs.existsSync(widgetDir)) {
  app.use("/widgets", express.static(widgetDir));
}

const server = http.createServer(app);
wsServer.attach(server);

// Every MQTT update flows through here and is immediately broadcast to
// whichever WebSocket clients care about that item (Dashboard = all,
// Widget pages = just their own item_id).
mqttClient.connect((item_id, updated) => {
  wsServer.broadcast(item_id, updated);
});

// HiveMQ Cloud broker — connects in parallel using the same shared store.
// If HIVEMQ_HOST is not set in .env, this call is a no-op and is safely skipped.
hivemqClient.connect((item_id, updated) => {
  wsServer.broadcast(item_id, updated);
});

server.listen(env.PORT, "0.0.0.0", () => {
  console.log(`[Backend] Listening on http://localhost:${env.PORT}`);
  console.log(`[Backend] WebSocket endpoint: ws://localhost:${env.PORT}/ws`);
});

