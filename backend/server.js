// Card styles API
app.get(["/api/card-styles", "/api/styles"], (req, res) => {
  const jsonPath = path.join(widgetDir, "custom-styles.json");
  if (fs.existsSync(jsonPath)) {
    try {
      const data = JSON.parse(fs.readFileSync(jsonPath, "utf-8"));
      return res.json({ ok: true, styles: data });
    } catch (e) {
      return res.status(500).json({ ok: false, error: e.message });
    }
  }
  res.json({ ok: true, styles: {} });
});

app.post(["/api/card-styles", "/api/styles"], (req, res) => {
  try {
    const styles = req.body || {};
    const jsonPath = path.join(widgetDir, "custom-styles.json");
    const cssPath = path.join(widgetDir, "css", "custom-cards.css");

    fs.writeFileSync(jsonPath, JSON.stringify(styles, null, 2), "utf-8");

    // Helper to generate CSS
    let css = `/* Generated by Widget Visual Editor */\n\n`;
    const standardCards = [
      { key: "preheating", selector: 'body[data-card="preheating"]' },
      { key: "kiln", selector: 'body[data-card="kiln"]' },
      { key: "cooler", selector: 'body[data-card="cooler"]' }
    ];

    standardCards.forEach(({ key, selector }) => {
      const s = styles[key];
      if (!s) return;
      css += `${selector} .card {\n`;
      if (s.cardWidth) css += `  width: ${s.cardWidth}px !important;\n`;
      if (s.cardPaddingY || s.cardPaddingX) css += `  padding: ${s.cardPaddingY || 13}px ${s.cardPaddingX || 15}px !important;\n`;
      if (s.cardRadius) css += `  border-radius: ${s.cardRadius}px !important;\n`;
      if (s.cardGap) css += `  gap: ${s.cardGap}px !important;\n`;
      css += `}\n`;
      if (s.headerPaddingBottom) css += `${selector} .card-header {\n  padding-bottom: ${s.headerPaddingBottom}px !important;\n}\n`;
      if (s.titleFontSize) css += `${selector} .card-title {\n  font-size: ${s.titleFontSize}px !important;\n}\n`;
      if (s.iconFontSize) css += `${selector} .card-icon {\n  font-size: ${s.iconFontSize}px !important;\n}\n`;
      if (s.sensorBoxPaddingY || s.sensorBoxPaddingX || s.sensorBoxRadius) {
        css += `${selector} .sensor-box {\n`;
        if (s.sensorBoxPaddingY || s.sensorBoxPaddingX) css += `  padding: ${s.sensorBoxPaddingY || 8}px ${s.sensorBoxPaddingX || 10}px !important;\n`;
        if (s.sensorBoxRadius) css += `  border-radius: ${s.sensorBoxRadius}px !important;\n`;
        css += `}\n`;
      }
      if (s.sensorLabelFontSize) css += `${selector} .sensor-label {\n  font-size: ${s.sensorLabelFontSize}px !important;\n}\n`;
      if (s.sensorValueFontSize) css += `${selector} .sensor-value {\n  font-size: ${s.sensorValueFontSize}px !important;\n}\n`;
      if (s.sensorUnitFontSize) css += `${selector} .sensor-unit {\n  font-size: ${s.sensorUnitFontSize}px !important;\n}\n`;
      if (s.controlPaddingY || s.controlPaddingX || s.controlGap || s.controlRadius) {
        css += `${selector} .control-row {\n`;
        if (s.controlPaddingY || s.controlPaddingX) css += `  padding: ${s.controlPaddingY || 8}px ${s.controlPaddingX || 12}px !important;\n`;
        if (s.controlGap) css += `  gap: ${s.controlGap}px !important;\n`;
        if (s.controlRadius) css += `  border-radius: ${s.controlRadius}px !important;\n`;
        css += `}\n`;
      }
      if (s.controlNameFontSize) css += `${selector} .control-name {\n  font-size: ${s.controlNameFontSize}px !important;\n}\n`;
      if (s.btnFontSize || s.btnPaddingY || s.btnPaddingX || s.btnRadius) {
        css += `${selector} .state-btn {\n`;
        if (s.btnFontSize) css += `  font-size: ${s.btnFontSize}px !important;\n`;
        if (s.btnPaddingY || s.btnPaddingX) css += `  padding: ${s.btnPaddingY || 5}px ${s.btnPaddingX || 13}px !important;\n`;
        if (s.btnRadius) css += `  border-radius: ${s.btnRadius}px !important;\n`;
        css += `}\n`;
      }
      css += `\n`;
    });

    if (styles.hopper) {
      const s = styles.hopper;
      css += `body[data-card="hopper"] .card {\n`;
      if (s.cardWidth) css += `  width: ${s.cardWidth}px !important;\n`;
      if (s.cardPaddingY || s.cardPaddingX) css += `  padding: ${s.cardPaddingY || 16}px ${s.cardPaddingX || 16}px !important;\n`;
      if (s.cardRadius) css += `  border-radius: ${s.cardRadius}px !important;\n`;
      css += `}\n`;
      if (s.titleFontSize) css += `body[data-card="hopper"] .card-title {\n  font-size: ${s.titleFontSize}px !important;\n}\n`;
      if (s.sensorValueFontSize) css += `body[data-card="hopper"] .card-value {\n  font-size: ${s.sensorValueFontSize}px !important;\n}\n`;
      if (s.sensorUnitFontSize) css += `body[data-card="hopper"] .card-unit {\n  font-size: ${s.sensorUnitFontSize}px !important;\n}\n`;
    }

    if (!fs.existsSync(path.join(widgetDir, "css"))) {
      fs.mkdirSync(path.join(widgetDir, "css"), { recursive: true });
    }
    fs.writeFileSync(cssPath, css, "utf-8");
    res.json({ ok: true, message: "Styles saved!" });
  } catch (err) {
    res.status(500).json({ ok: false, error: err.message });
  }
});

if (fs.existsSync(widgetDir)) {
  app.use("/widgets", express.static(widgetDir));
}

const server = http.createServer(app);
wsServer.attach(server);

// Every MQTT update flows through here and is immediately broadcast to
// whichever WebSocket clients care about that item (Dashboard = all,
// Widget pages = just their own item_id).
mqttClient.connect((item_id, updated) => {
  wsServer.broadcast(item_id, updated);
});

// HiveMQ Cloud broker — connects in parallel using the same shared store.
// If HIVEMQ_HOST is not set in .env, this call is a no-op and is safely skipped.
hivemqClient.connect((item_id, updated) => {
  wsServer.broadcast(item_id, updated);
});

server.listen(env.PORT, "0.0.0.0", () => {
  console.log(`[Backend] Listening on http://localhost:${env.PORT}`);
  console.log(`[Backend] WebSocket endpoint: ws://localhost:${env.PORT}/ws`);
});

